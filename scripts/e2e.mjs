// End-to-End-Test gegen einen laufenden Server (AI_JOURNAL_FAKE_PROVIDER=1, frischer Journal-Ordner, Port 8790).
// Aufruf: S=<Screenshot-Ordner> node scripts/e2e.mjs   (braucht ein installiertes "playwright"-Paket)
import { chromium } from "playwright";
const S = process.env.S, B = "http://127.0.0.1:8790";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 860 }, deviceScaleFactor: 1 });
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
page.on("console", (m) => { if (m.type() === "error") console.log("CONSOLE", m.text()); });
const shot = (n) => page.screenshot({ path: `${S}/shot-${n}.png` });

await page.goto(B);
await page.waitForSelector("input[placeholder=PIN]");
await shot("1-setup");
await page.fill("input[placeholder=PIN]", "1234");
await page.fill("input[placeholder='PIN wiederholen']", "1234");
await page.click("button:has-text('Festlegen')");
await page.waitForSelector(".cm-editor");
console.log("entry view loaded, url", page.url());
await page.click(".cm-content");
await page.keyboard.press("Control+End");
await page.keyboard.type("Heute lief das Projekt gut, aber ich habe wieder die Steuer verschoben. *kursiv* **fett**");
await page.click("button[title='Energie 4']");
await page.click("button[title='Fokus 3']");
await page.waitForTimeout(1500);
await shot("2-editor");
console.log("save state:", (await page.textContent(".state")).trim());
await page.fill("input[placeholder^='Schnellnotiz']", "Kurz zwischendurch");
await page.click("button:has-text('Anhängen')");
await page.waitForTimeout(800);
const text = await page.evaluate(() => document.querySelector(".cm-content").textContent);
console.log("editor contains quicknote:", text.includes("Kurz zwischendurch"), "| contains typed:", text.includes("Steuer"));
await page.click("button[title='Vortag']");
await page.waitForSelector("text=keinen Eintrag");
await page.click("button:has-text('Eintrag anlegen')");
await page.waitForSelector(".cm-editor");
await page.click(".cm-content");
await page.keyboard.type("Gestern: Steuer nicht gemacht.");
await page.waitForTimeout(1300);
await page.click("a[href='#/reports']");
await page.waitForSelector("text=Aktuelle Zeiträume");
await shot("3-reports");
const weeklyCell = page.locator(".cell", { hasText: "Wöchentlich" });
await weeklyCell.locator("button:has-text('jetzt erzeugen')").click();
await page.waitForTimeout(5000);
await shot("4-reports-after");
const list = await page.locator(".list a").allTextContents();
console.log("report list:", list.map((s) => s.replace(/\s+/g, " ").trim()));
await page.locator(".list a").first().click();
await page.waitForSelector(".md h1");
console.log("report h1:", await page.textContent(".md h1"));
await shot("5-report");
await page.click("a[href='#/settings']");
await page.click("button:has-text('Gedächtnis')");
await page.waitForSelector("text=themen.md");
await shot("6-settings-memory");
await page.click("button:has-text('KI')");
await page.waitForSelector("select");
await page.click("button:has-text('Speichern und testen')");
await page.waitForSelector(".ok, .error", { timeout: 15000 });
console.log("provider test:", await page.textContent(".ok, .error"));
await page.click("a[href='#/search']");
await page.fill("input[type=search]", "steuer");
await page.press("input[type=search]", "Enter");
await page.waitForSelector(".list a");
console.log("search hits:", await page.locator(".list a").count());
await shot("7-search");
await page.click("button[title='Menü ausblenden']");
await page.waitForTimeout(400);
await shot("8-collapsed");
await page.click("button[title='Menü einblenden']");
await page.click("button[title='Sperren']");
await page.waitForSelector("input[placeholder=PIN]");
await page.fill("input[placeholder=PIN]", "9999");
await page.click("button:has-text('Entsperren')");
await page.waitForSelector(".error");
console.log("wrong pin:", await page.textContent(".error"));
await page.fill("input[placeholder=PIN]", "1234");
await page.click("button:has-text('Entsperren')");
await page.waitForSelector(".sidebar");
console.log("unlocked ok, route:", page.url());
await page.click("a[href^='#/entry/']");
await page.waitForSelector(".cm-editor");
await page.setViewportSize({ width: 390, height: 800 });
await page.waitForTimeout(400);
await shot("9-mobile");
await browser.close();
